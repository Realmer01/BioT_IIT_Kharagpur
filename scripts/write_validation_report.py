"""Render docs/VALIDATION_REPORT.md from reports/*.json (keeps the report in sync with the results).

Usage:  python scripts/write_validation_report.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from madhutwin.config import REPORTS  # noqa: E402

DOC = Path(__file__).resolve().parent.parent / "docs" / "VALIDATION_REPORT.md"
H = ["30", "60", "90", "120"]
MAIN = "MadhuTwin hybrid"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" if i == 0 else "---:" for i in range(len(header))) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def bold_if(name, s):
    return f"**{s}**" if name == MAIN or name.startswith(MAIN) else s


def main():
    m = json.load(open(REPORTS / "metrics_cgmacros.json"))
    b = json.load(open(REPORTS / "metrics_bharat.json"))
    tv = json.load(open(REPORTS / "twin_value.json"))
    d = m["dataset"]
    reg = m["regression"]
    L = []
    L.append("# Validation report\n")
    L.append("*Generated by `scripts/write_validation_report.py` from `reports/*.json`. Do not edit by hand.*\n")
    L.append("## Protocol\n")
    L.append(f"- **Data:** CGMacros (PhysioNet), {d['participants']} adults: {d['groups'].get('normal')} normoglycaemic, "
             f"{d['groups'].get('prediabetes')} prediabetes, {d['groups'].get('t2d')} type 2 diabetes. Dexcom G6 CGM (native 5-min samples only), "
             "Fitbit heart rate and METs, logged meals with macros, fasting labs.")
    L.append("- **Split:** 5-fold leave-patients-out cross-validation, stratified by glycaemic group. Test patients are never seen by the ML layer.")
    L.append("- **Twin personalisation:** each test patient's twin is fitted only on their own onboarding window (first 40 % of the record, at most 4 days). "
             f"All metrics use the later monitoring period: {d['test_rows']:,} forecasts over {d['monitored_days']:.0f} patient-days.")
    L.append("- **Fair comparison:** every model is trained and scored on identical rows; only the inputs differ.")
    L.append("- **Leakage control:** CGMacros interpolates CGM to 1-minute resolution; we recover the native sensor grid and use only true samples. "
             "A unit test verifies that features at minute *t* are unchanged when later data is removed.\n")

    L.append("## 1. Glucose forecasting (all windows, unconditional)\n")
    L.append("RMSE in mg/dL (lower is better). Clarke error grid A+B = clinically acceptable.\n")
    rows = []
    for n, v in reg.items():
        rows.append([bold_if(n, n)] + [f"{v[h]['rmse']:.1f}" for h in H] + [f"{v['60']['mard']:.1f}", f"{v['120']['clarke_ab']:.1f}"])
    L.append(table(["Model", "30 min", "60 min", "90 min", "120 min", "MARD 60 min (%)", "Clarke A+B 120 min (%)"], rows) + "\n")
    L.append("**After meals** (forecasts made within 3 h of a logged meal):\n")
    rows = [[bold_if(n, n)] + [f"{v[h]['rmse']:.1f}" for h in H] for n, v in m["regression_postprandial"].items()]
    L.append(table(["Model", "30", "60", "90", "120"], rows) + "\n")
    L.append("**Type 2 diabetes participants only:**\n")
    rows = [[bold_if(n, n)] + [f"{v['t2d'][h]['rmse']:.1f}" for h in H] for n, v in m["regression_by_group"].items()]
    L.append(table(["Model", "30", "60", "90", "120"], rows) + "\n")

    if "regression_conditional" in m:
        L.append("## 2. Conditional forecasts (\"if no new food is eaten\")\n")
        L.append("The deployed forecaster is trained and scored on windows with no logged meal inside the horizon, matching the twin's "
                 "assumption that new meals enter through simulation. Scored on meal-free windows only.\n")
        rows = [[bold_if(n, n)] + [f"{v[h]['rmse']:.1f}" for h in H] for n, v in m["regression_conditional"].items()]
        L.append(table(["Model", "30", "60", "90", "120"], rows) + "\n")

    L.append("## 3. Uncertainty calibration\n")
    rows = [[h + " min", f"{v['nominal'] * 100:.0f}%", f"{v['coverage'] * 100:.1f}%", f"{v['mean_width']:.0f}"] for h, v in m["intervals"].items()]
    L.append(table(["Horizon", "Nominal", "Observed coverage", "Mean width (mg/dL)"], rows) + "\n")

    L.append("## 4. Adverse-event prediction\n")
    names = {"ev_hyper": "Hyperglycaemia onset (>180 mg/dL within 2 h, currently ≤180)", "ev_spike": "Spike (rise ≥50 mg/dL within 2 h)",
             "ev_hypo": "Hypoglycaemia onset (<70 mg/dL within 1 h, currently ≥70)"}
    for ev, title in names.items():
        L.append(f"**{title}**\n")
        rows = []
        for n, v in m["events"][ev].items():
            if "auroc" in v:
                rows.append([bold_if(n, n), f"{v['prevalence'] * 100:.2f}%", f"{v['auroc']:.3f}", f"{v['auprc']:.3f}", f"{v['brier']:.3f}"])
        L.append(table(["Inputs", "Prevalence", "AUROC", "AUPRC", "Brier"], rows) + "\n")
    L.append("**Episode-level early warning of hyperglycaemia** (alert threshold 0.5):\n")
    rows = [[bold_if(n, n), v["episodes"], f"{v['episode_sensitivity'] * 100:.0f}%", f"{v['median_lead_min']:.0f}", f"{v['false_alerts_per_day']:.2f}"]
            for n, v in m["episodes"].items()]
    L.append(table(["Inputs", "Episodes", "Flagged ≥15 min ahead", "Median lead (min)", "False alerts/day"], rows) + "\n")

    L.append("## 5. Personal meal-response prediction\n")
    pp = m["meal_ppgr"]
    L.append(f"Peak glucose rise within 2 h of {pp['n_meals_test']} isolated meals in the monitoring period (no other meal within 90 min).\n")
    rows = [[bold_if(n, n), f"{v['pearson_r']:.3f}", f"{v['p_value']:.1e}", f"{v['mae']:.1f}"] for n, v in pp["models"].items()]
    L.append(table(["Model", "Pearson r", "p", "MAE (mg/dL)"], rows) + "\n")

    L.append("## 6. The physiological twin itself\n")
    t = m["twin"]
    rows = [[h + " min", f"{t['prior_rmse'][h]:.1f}", f"{t['personalised_rmse'][h]:.1f}"] for h in H]
    L.append("Physiology-only forecast error on the onboarding window, before (EHR prior) and after personalisation:\n")
    L.append(table(["Horizon", "EHR prior twin", "Personalised twin"], rows) + "\n")
    L.append(f"Plausibility across participants (Spearman): twin insulin sensitivity vs HOMA-IR ρ = {t['si_vs_homa_ir_spearman']:.2f}; "
             f"twin disposition index vs HbA1c ρ = {t['di_vs_hba1c_spearman']:.2f}; twin basal glucose vs lab fasting glucose ρ = {t['gb_vs_fpg_spearman']:.2f}. "
             "The priors use HOMA-IR and fasting glucose, so these correlations partly reflect the prior by design.\n")
    cs = tv["cold_start"]["table"]
    rows = [[d_, f"{cs[f'EHR prior|{d_}']['rmse_60']:.1f}", f"{cs[f'Population prior|{d_}']['rmse_60']:.1f}",
             f"{cs[f'EHR prior|{d_}']['rmse_120']:.1f}", f"{cs[f'Population prior|{d_}']['rmse_120']:.1f}"] for d_ in ("0.0", "0.5", "1.0", "2.0", "4.0")]
    L.append("**Cold start:** twin-only RMSE on the later test period vs days of onboarding data, with the patient's own EHR prior or a one-size-fits-all population prior:\n")
    L.append(table(["Onboarding days", "EHR prior 60 min", "Population prior 60 min", "EHR prior 120 min", "Population prior 120 min"], rows) + "\n")

    L.append("## 7. Bharat synthetic cohort (SYNTHETIC: tests the pipeline, not real-world accuracy)\n")
    L.append(f"{b['n_patients']} fictional Indian patients, 5 folds; each fold trains on all CGMacros participants plus four fifths of the cohort. "
             f"{b['note']}.\n")
    rows = [[bold_if(n, n)] + [f"{v[h]['rmse']:.1f}" for h in H] for n, v in b["regression"].items()]
    L.append(table(["Model", "30", "60", "90", "120"], rows) + "\n")
    rows = []
    for ev, title in names.items():
        for n, v in b["events"][ev].items():
            if "auroc" in v:
                rows.append([title.split(" (")[0], bold_if(n, n), f"{v['prevalence'] * 100:.2f}%", f"{v['auroc']:.3f}", f"{v['auprc']:.3f}"])
    L.append(table(["Event", "Model", "Prevalence", "AUROC", "AUPRC"], rows) + "\n")
    if "episodes_hypo_by_threshold" in b:
        rows = [[thr, v["episodes"], f"{v['episode_sensitivity'] * 100:.0f}%", f"{v['median_lead_min']:.0f}", f"{v['false_alerts_per_day']:.2f}"]
                for thr, v in b["episodes_hypo_by_threshold"].items()]
        L.append("**Hypoglycaemia episodes** (onset below 70 mg/dL; flagged ≥10 min ahead). The dashboard alerts at 0.25:\n")
        L.append(table(["Alert threshold", "Episodes", "Flagged ≥10 min ahead", "Median lead (min)", "False alerts/day"], rows) + "\n")

    L.append("## 8. Negative results we kept\n")
    L.append("- **Disturbance observer** (integral state absorbing unexplained glucose flux): no benefit in a grid search; disabled.")
    L.append("- **Activity-persistence prior** (assume an ongoing walk continues and tapers): no accuracy gain on either cohort, slightly worse beyond 30 min; disabled.")
    L.append("- **Twin features in rolling forecasts:** on real data, adding twin features to the ML layer did not improve RMSE over the best fusion model. "
             "The twin's measured value lies in counterfactual simulation, day-zero personalisation from the EHR, meal-response prediction and interpretable physiology.")
    L.append("- **Static EHR features in short-term forecasts:** add little once CGM is available (36 training patients per fold); their effect appears through the twin prior and baseline risk.\n")
    DOC.write_text("\n".join(L), encoding="utf-8")
    print("wrote", DOC)


if __name__ == "__main__":
    main()
